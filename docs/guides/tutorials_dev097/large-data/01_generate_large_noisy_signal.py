# GX-TXT Python Script Workspace tutorial:
# generate a multi-million-sample HDF5 Dataset containing deterministic
# multi-tone signal + framework-generated white Gaussian noise.
#
# Scientific waveform/noise generation uses SIGNAL_API_v1.
# Array combination uses NUMERIC_API_v1.
# Publication uses DATASET_PUBLICATION_API_v2.
#
# SPDX-License-Identifier: GPL-3.0-or-later

from gxtxt import gxtxt_context, gxtxt_api_require, gxtxt_api_call
import numpy as np
import time


DATASET_ID = "tutorial.large_noisy_multitone"

SAMPLE_RATE_HZ = 65536.0
SAMPLE_COUNT = 1 << 22          # 4,194,304 samples
CHUNK_SAMPLES = 1 << 18         # 262,144 samples
BASE_SEED = 20261006

TONE_FREQUENCIES_HZ = np.asarray([997.0, 4093.0, 12011.0], dtype=float)
TONE_AMPLITUDES_V = np.asarray([1.0, 0.35, 0.15], dtype=float)
WHITE_NOISE_RMS_V = 0.20


def signal_empty():
    return {"kind": "empty"}


def signal_array(values):
    array = np.asarray(values, dtype=float).reshape(-1)
    return {
        "kind": "array",
        "shape": [int(array.size), 1],
        "real": array,
    }


def signal_scalar(value):
    return signal_array(np.asarray([float(value)], dtype=float))


def signal_struct(fields):
    return {"kind": "struct", "fields": fields}


def signal_values(result, field="value_real"):
    if field not in result:
        raise RuntimeError(f"LARGE_GENERATE: SIGNAL_API_v1 result lacks {field}")
    return np.asarray(result[field], dtype=float).reshape(-1)


def numeric_vector(values):
    return {"kind": "vector", "value": np.asarray(values, dtype=float).reshape(-1)}


def numeric_binary(operation, left, right):
    result = gxtxt_api_call(
        "NUMERIC_API_v1",
        "array_binary",
        [operation, numeric_vector(left), numeric_vector(right)],
    )
    return np.asarray(result["values"], dtype=float).reshape(-1)


ctx = gxtxt_context()

gxtxt_api_require([
    "SIGNAL_API_v1@1:math.signal",
    "NUMERIC_API_v1@1:math.numeric",
    "DATASET_PUBLICATION_API_v2@2",
    "DATASET_METADATA_API_v1@1",
    "PARALLEL_EXECUTION_API_v1@1",
    "SESSION_PERSISTENCE_API_v1@1",
])

if SAMPLE_COUNT % CHUNK_SAMPLES != 0:
    raise RuntimeError("LARGE_GENERATE: tutorial constants require an integer number of chunks")

parallel_policy = gxtxt_api_call(
    "PARALLEL_EXECUTION_API_v1", "resources", []
)

definition = {
    "dataset_id": DATASET_ID,
    "contract": "table.generic",
    "storage": "hdf5",
    "replace_owned": True,
    "producer_version": "1.0.0",
    "source": "Python Script Workspace large noisy signal generator",
    "provenance": (
        "Deterministic framework-generated multi-tone signal plus seeded white "
        "Gaussian noise. Waveforms generated through SIGNAL_API_v1 and combined "
        "through NUMERIC_API_v1. Published directly as chunked HDF5."
    ),
    "notes": (
        "Large-data tutorial Dataset. Time is an implicit uniform coordinate; "
        "only the signal payload is physically stored in HDF5."
    ),
}

writer = gxtxt_api_call(
    "DATASET_PUBLICATION_API_v2", "begin", [definition]
)

generation_start = time.perf_counter()
try:
    gxtxt_api_call(
        "DATASET_PUBLICATION_API_v2",
        "declare_dimension",
        [writer, "sample", 0, {"extendible": 1}],
    )

    # Uniform time is framework-owned coordinate metadata. HDF5 reconstructs
    # requested ranges without storing a full time vector.
    time_schema = {
        "dtype": "float64",
        "rank": 1,
        "dimension_ids": "sample",
        "coordinate_role": "coordinate",
        "axis_kind": "uniform",
        "axis_origin": 0.0,
        "axis_step": 1.0 / SAMPLE_RATE_HZ,
        "unit": "s",
        "semantic_role": "elapsed_time",
    }
    gxtxt_api_call(
        "DATASET_PUBLICATION_API_v2",
        "declare_variable",
        [writer, "v_time_s", time_schema],
    )

    signal_schema = {
        "dtype": "float64",
        "rank": 1,
        "dimension_ids": "sample",
        "coordinate_variable_ids": "v_time_s",
        "coordinate_role": "data",
        "unit": "V",
        "semantic_role": "voltage",
        "chunks": str(CHUNK_SAMPLES),
    }
    gxtxt_api_call(
        "DATASET_PUBLICATION_API_v2",
        "declare_variable",
        [writer, "v_signal_v", signal_schema],
    )

    chunk_count = SAMPLE_COUNT // CHUNK_SAMPLES

    for chunk_index in range(chunk_count):
        offset = chunk_index * CHUNK_SAMPLES

        # NumPy is used only to construct the chunk-local coordinate vector
        # required by SIGNAL_API_v1. The signal and noise themselves are
        # generated by the framework.
        time_values = (
            np.arange(offset, offset + CHUNK_SAMPLES, dtype=float)
            / SAMPLE_RATE_HZ
        )

        tone_result = gxtxt_api_call(
            "SIGNAL_API_v1",
            "generate.multi_tone",
            [
                signal_array(time_values),
                signal_array(TONE_FREQUENCIES_HZ),
                signal_empty(),
                signal_struct({
                    "amplitudes": signal_array(TONE_AMPLITUDES_V),
                    "phase_rad": signal_scalar(0.0),
                }),
            ],
        )

        noise_result = gxtxt_api_call(
            "SIGNAL_API_v1",
            "generate.white_noise",
            [
                signal_array(time_values),
                signal_empty(),
                signal_empty(),
                signal_struct({
                    "seed": signal_scalar(BASE_SEED + chunk_index),
                    "amplitude": signal_scalar(WHITE_NOISE_RMS_V),
                }),
            ],
        )

        tone = signal_values(tone_result)
        noise = signal_values(noise_result)

        if tone.size != CHUNK_SAMPLES or noise.size != CHUNK_SAMPLES:
            raise RuntimeError(
                f"LARGE_GENERATE: unexpected generated chunk length at chunk {chunk_index}"
            )

        combined = numeric_binary("add", tone, noise)

        gxtxt_api_call(
            "DATASET_PUBLICATION_API_v2",
            "append",
            [writer, "sample", {"v_signal_v": combined}],
        )

        elapsed = time.perf_counter() - generation_start
        print(
            f"LARGE_GENERATE chunk={chunk_index + 1}/{chunk_count} "
            f"rows={(chunk_index + 1) * CHUNK_SAMPLES} "
            f"elapsed={elapsed:.3f}s"
        )

    published = gxtxt_api_call(
        "DATASET_PUBLICATION_API_v2", "finalize", [writer]
    )
    writer = None
except Exception:
    if writer is not None:
        gxtxt_api_call("DATASET_PUBLICATION_API_v2", "abort", [writer])
    raise

generation_seconds = time.perf_counter() - generation_start
samples_per_second = SAMPLE_COUNT / generation_seconds

metadata = {
    "demo.type": "python_large_signal_generation",
    "demo.domain": "signal_processing",
    "generation.signal_api": "SIGNAL_API_v1",
    "generation.numeric_api": "NUMERIC_API_v1",
    "generation.waveform": "multi_tone_plus_white_gaussian_noise",
    "generation.sample_rate_hz": f"{SAMPLE_RATE_HZ:.17g}",
    "generation.sample_count": str(SAMPLE_COUNT),
    "generation.duration_s": f"{SAMPLE_COUNT / SAMPLE_RATE_HZ:.17g}",
    "generation.chunk_samples": str(CHUNK_SAMPLES),
    "generation.chunk_count": str(SAMPLE_COUNT // CHUNK_SAMPLES),
    "generation.base_seed": str(BASE_SEED),
    "generation.seed_mode": "base_seed_plus_chunk_index",
    "generation.tone_frequencies_hz": ",".join(
        f"{v:.17g}" for v in TONE_FREQUENCIES_HZ
    ),
    "generation.tone_amplitudes_v": ",".join(
        f"{v:.17g}" for v in TONE_AMPLITUDES_V
    ),
    "generation.white_noise_rms_v": f"{WHITE_NOISE_RMS_V:.17g}",
    "storage.requested": "hdf5",
    "storage.time_coordinate": "implicit_uniform",
    "schema.time_variable_id": "v_time_s",
    "schema.signal_variable_id": "v_signal_v",
    "performance.generation_seconds": f"{generation_seconds:.17g}",
    "performance.generation_samples_per_second": f"{samples_per_second:.17g}",
    "parallel.policy_enabled": str(parallel_policy.get("enabled", "")),
    "parallel.default_workers": str(parallel_policy.get("default_workers", "")),
    "parallel.max_workers": str(parallel_policy.get("max_workers", "")),
    "parallel.recommended_internal_threads": str(
        parallel_policy.get("recommended_internal_threads", "")
    ),
}

gxtxt_api_call(
    "DATASET_METADATA_API_v1", "update", [DATASET_ID, metadata]
)
gxtxt_api_call("SESSION_PERSISTENCE_API_v1", "commit", [])

print(
    "PASS LARGE_SIGNAL_GENERATION "
    f"dataset={published['dataset_id']} "
    f"samples={SAMPLE_COUNT} fs={SAMPLE_RATE_HZ:g}Hz "
    f"duration={SAMPLE_COUNT / SAMPLE_RATE_HZ:g}s "
    f"storage=hdf5 seconds={generation_seconds:.6g} "
    f"throughput={samples_per_second:.6g} samples/s"
)
