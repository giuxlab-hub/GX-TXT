% Internal registry for Scientific Analysis Definition API v1 operation types.
% Public descriptor syntax remains API v1. Numerical kernels are resolved here
% so future operations can be added without creating a second public API.
function out = gxtxt_analysis_operation_registry(action,name)
  if(nargin<1||isempty(action)),action='all';endif
  R=registry();
  switch lower(action)
    case 'all',out={R.name};
    case 'has',out=any(strcmp({R.name},name));
    case 'kind'
      k=find(strcmp({R.name},name),1);if(isempty(k)),out='';else out=R(k).kind;endif
    case 'handler'
      k=find(strcmp({R.name},name),1);if(isempty(k)),out='';else out=R(k).handler;endif
    case 'canonical'
      k=find(strcmp({R.name},name),1);if(isempty(k)),out='';else out=R(k).canonical;endif
    case 'entries',out=R;
    otherwise,error('GXTXT:AnalysisRegistry','unknown registry action: %s',action);
  endswitch
endfunction
function R=registry()
  spec={ ...
    'expression','series','gxtxt_analysis_op_expression','expression'; ...
    'compare','series','gxtxt_analysis_op_compare','compare'; ...
    'normalize','series','gxtxt_analysis_op_normalize','normalize'; ...
    'aggregate','series','gxtxt_analysis_op_aggregate','aggregate'; ...
    'filter','series','gxtxt_analysis_op_filter','filter'; ...
    'select','series','','select'; ...
    'crossing','feature','gxtxt_analysis_op_crossing','crossing'; ...
    'mask','series','gxtxt_analysis_op_mask','mask'; ...
    'align','series','gxtxt_analysis_op_align','align'; ...
    'join','series','gxtxt_analysis_op_join','join'; ...
    'resample','series','gxtxt_analysis_op_align','resample'; ...
    'interpolate','series','gxtxt_analysis_op_interpolate','interpolate'; ...
    'peak','feature','gxtxt_analysis_op_extrema','extrema'; ...
    'extrema','feature','gxtxt_analysis_op_extrema','extrema'; ...
    'integrate','feature','gxtxt_analysis_op_integrate','integrate'; ...
    'area','feature','gxtxt_analysis_op_integrate','integrate'; ...
    'derivative','series','gxtxt_analysis_op_derivative','derivative'; ...
    'slope','series','gxtxt_analysis_op_derivative','derivative'; ...
    'window','series','gxtxt_analysis_op_window','window'; ...
    'correlate','feature','gxtxt_analysis_op_correlate','correlate'; ...
    'regress','series','gxtxt_analysis_op_regress','regress'; ...
    'fit','series','gxtxt_analysis_op_fit','fit'; ...
    'convert_unit','series','gxtxt_unit_convert','convert_unit'};
  R=repmat(struct('name','','kind','','handler','','canonical',''),size(spec,1),1);
  for i=1:size(spec,1),R(i).name=spec{i,1};R(i).kind=spec{i,2};R(i).handler=spec{i,3};R(i).canonical=spec{i,4};endfor
endfunction
