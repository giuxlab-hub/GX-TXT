from gxtxt_script_bridge_server import BridgeError, NumericArray, ResourceNumericArray

_OPERATIONS = {"write": ("::GX::managedResourceWriteBase64", ["document_id", "metadata", "bytes_base64"]),
               "copy": ("::GX::managedResourceCopy", ["document_id", "resource"]),
               "write_numeric": (None, ["document_id", "columns", "values", "metadata"]),
               "read_numeric": ("::GX::managedResourceNumericPage", ["resource", "start", "count"]),
               "read": ("::GX::managedResourceReadBase64", ["resource", "start", "count"]),
               "info": ("::GX::interactiveDocumentResourceInfo", ["resource"])}
REGISTRATION = {
    "api_id": "MANAGED_RESOURCE_API_v1", "api_version": 1,
    "provider_kind": "core", "provider_id": "managed_resource",
    "documentation_ref": "docs/api/MANAGED_RESOURCE_API_v1.md",
    "operations": {name: {"name": name, "summary": "Bounded managed resource " + name,
                           "arguments": [{"name": arg, "kind": "public value", "required": True} for arg in args],
                           "result_contract": "bounded typed numeric binary page" if name == "read_numeric" else "managed resource receipt or bounded base64 data",
                           "argument_convention": ", ".join(args), "result_convention": "bounded public value"}
                   for name, (_, args) in _OPERATIONS.items()},
}


def invoke(host, operation, args):
    if operation not in _OPERATIONS or len(args) != len(_OPERATIONS[operation][1]):
        raise BridgeError("GXTXT:ScriptBridge:InvalidArguments", "Invalid managed resource arguments")
    if operation == "write" and (not isinstance(args[1], dict) or not isinstance(args[2], str)):
        raise BridgeError("GXTXT:ScriptBridge:InvalidArguments", "Resource write needs metadata and base64 text")
    if operation == "write_numeric":
        raw = _write_numeric(host, *args)
    else:
        raw = host.call(_OPERATIONS[operation][0], *args)
    if operation == "read":
        return raw.decode("ascii") if isinstance(raw, bytes) else str(raw)
    result = host.as_dict(raw)
    if operation == "read_numeric":
        import numpy as np
        from gxtxt_scientific_binary_v1 import DTYPES
        dtype = DTYPES[str(result['dtype'])]
        columns = [str(v) for v in host.as_list(result['columns'])]
        rows = int(result['row_count']);payload = result.pop('bytes')
        if rows == 0 and payload == '':
            payload = b''
        if not isinstance(payload, bytes) or len(payload) != rows*len(columns)*np.dtype(dtype).itemsize:
            raise BridgeError("GXTXT:ScriptBridge:Transport", "Numeric resource page lost its binary shape")
        values = np.frombuffer(payload, dtype=dtype).reshape(rows,len(columns))
        return {'schema':'gxtxt.numeric_resource_page.v1','values':NumericArray(values.ravel(order='F'),[rows,len(columns)]),
                'dtype':str(result['dtype']),'columns':columns,'start':int(result['start']),
                'row_count':rows,'total_rows':int(result['total_rows']),'source_sha256':str(result['source_sha256'])}
    result["size_bytes"] = int(result["size_bytes"])
    result["metadata"] = host.as_dict(result["metadata"])
    return result


def _write_numeric(host, document, columns, values, metadata):
    """Copy bounded typed rows once into the existing durable Document owner.

    Lazy Bridge inputs are mapped read-only; there is no whole-array copy or
    per-element Tcl/base64 conversion. The staging allocation belongs to CORE.
    """
    import os
    import numpy as np
    from gxtxt_scientific_binary_v1 import DTYPES, shape_checked, open_buffer
    from gxtxt_resource_manager import ResourceManager

    if (not isinstance(values, NumericArray) or not isinstance(metadata, dict)
            or not isinstance(columns, (list, tuple)) or not 1 <= len(columns) <= 128
            or any(not isinstance(c, str) or not c.strip() or any(ord(x) < 32 for x in c) for c in columns)
            or len(set(columns)) != len(columns)):
        raise BridgeError('GXTXT:ScriptBridge:InvalidArguments', 'Typed resource needs a numeric array, distinct column IDs and metadata')
    reserved = {'dtype', 'endian', 'order', 'row_count', 'columns', 'point_count'}
    if reserved.intersection(metadata):
        raise BridgeError('GXTXT:ScriptBridge:InvalidArguments', 'Numeric shape/dtype metadata is generated by CORE')
    dtype = DTYPES.get(values.dtype)
    shape = list(values.shape)
    if len(shape) == 1:
        shape.append(1)
    if dtype is None or len(shape) != 2 or shape[1] != len(columns):
        raise BridgeError('GXTXT:ScriptBridge:InvalidArguments', 'Numeric resource shape must be rows by declared columns')
    count = shape_checked(shape, np.dtype(dtype).itemsize)
    fmt = metadata.get('format', 'gxtxt.numeric_matrix_le_v1')
    if fmt not in ('gxtxt.numeric_matrix_le_v1', 'native2d.float64_xy_le_v1', 'native2d.uint8_break_before_v1', 'float64_interleaved_le', 'uint64_le'):
        raise BridgeError('GXTXT:ScriptBridge:InvalidArguments', 'Unsupported typed numeric resource format')
    if ((fmt == 'float64_interleaved_le' and values.dtype != 'float64') or
            (fmt == 'uint64_le' and (values.dtype != 'uint64' or len(columns) != 1))):
        raise BridgeError('GXTXT:ScriptBridge:InvalidArguments', 'Canonical resource format differs from its numeric dtype or columns')
    if fmt == 'native2d.float64_xy_le_v1' and (values.dtype != 'float64' or list(columns) != ['x', 'y'] or not shape[0]):
        raise BridgeError('GXTXT:ScriptBridge:InvalidArguments', 'Native2D geometry needs nonempty float64 X/Y columns')
    if fmt == 'native2d.uint8_break_before_v1' and (values.dtype != 'uint8' or list(columns) != ['break_before'] or not shape[0]):
        raise BridgeError('GXTXT:ScriptBridge:InvalidArguments', 'Native2D gaps need a nonempty uint8 break_before column')
    generation = host.call('::GX::managedResourceNumericOwner', document)
    captured = dict(metadata, format=fmt, dtype=values.dtype, endian='little', order='C',
                    columns=list(columns), row_count=shape[0])
    manager = ResourceManager()
    allocation = None
    mapped = None
    try:
        allocation = manager.allocate('managed_numeric_import', kind='file', suffix='.bin',
                                      job_id=host.run_id, session=host.session,
                                      expected_bytes=count*np.dtype(dtype).itemsize)
        if isinstance(values, ResourceNumericArray) and count:
            fd, checked_dtype, checked_count = open_buffer(values.root, values.descriptor)
            try:
                if checked_count != count or np.dtype(checked_dtype) != np.dtype(dtype):
                    raise BridgeError('GXTXT:ScriptBridge:Transport', 'Numeric resource descriptor changed')
                with os.fdopen(fd, 'rb', closefd=False) as stream:
                    mapped = np.memmap(stream, dtype=checked_dtype, mode='r', shape=shape, order='F')
            finally:
                os.close(fd)
            array = mapped
        elif count:
            array = values.values.reshape(shape, order='F')
        else:
            array = np.empty(shape, dtype=dtype)
        rows_per_block = max(1, 1048576 // (shape[1]*np.dtype(dtype).itemsize))
        with open(allocation['path'], 'wb') as stream:
            for start in range(0, shape[0], rows_per_block):
                block = np.ascontiguousarray(array[start:start+rows_per_block], dtype=dtype)
                stream.write(memoryview(block).cast('B'))
        return host.call('::GX::managedResourceImportNumeric', document, generation, allocation['path'], captured)
    finally:
        if mapped is not None:
            mapped._mmap.close()
        try:
            if allocation is not None:
                manager.release(allocation['id'])
                manager.cleanup([allocation['id']])
        finally:
            manager.close()
