#!/usr/bin/env python3
"""Generate a deterministic 38 kHz NEC-family infrared waveform."""
import argparse
import csv
import math
from pathlib import Path
from session_recipe import configure

FS = 2_000_000
CARRIER = 38_000
BYTES = (0x08, 0xF7, 0xB2, 0x4D)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--target-session', required=True)
    parser.add_argument('--library-id')
    parser.add_argument('--generator-id')
    root = Path(parser.parse_args().target_session)
    for name in ('raw', 'metadata', 'notes/experiment'):
        (root / name).mkdir(parents=True, exist_ok=True)
    marks = []
    t = 0.0
    def mark(duration):
        nonlocal t
        marks.append((t, t + duration))
        t += duration
    def space(duration):
        nonlocal t
        t += duration
    mark(.009)
    space(.0045)
    for byte in BYTES:
        for bit in range(8):
            mark(.00056)
            space(.00169 if byte & (1 << bit) else .00056)
    mark(.00056)
    end = t + .01
    total = math.floor((end + .01) * FS) + 1
    mark_index = 0
    with (root / 'raw/ir_remote_nec.csv').open('w', encoding='utf-8', newline='') as stream:
        writer = csv.writer(stream)
        writer.writerow(('time_s', 'VIR'))
        for i in range(total):
            time = i / FS - .01
            while mark_index < len(marks) and time > marks[mark_index][1]:
                mark_index += 1
            value = 0
            if mark_index < len(marks):
                start, stop = marks[mark_index]
                if start <= time <= stop and ((time - start) * CARRIER) % 1 < .33:
                    value = -1
            writer.writerow((f'{time:.12g}', value))
    (root / 'metadata/ir_remote_ground_truth.txt').write_text(
        f'sample_rate_hz={FS}\ncarrier_hz={CARRIER}\nprotocol_family=NEC\n'
        f'payload_hex=08 F7 B2 4D\nbit_count=32\nrows={total}\n', encoding='utf-8')
    objective = '''# Experiment objective

Recover a 38 kHz infrared carrier and the MARK/SPACE timing of a deterministic 32-bit NEC-family remote-control command. Compare the identified protocol and decoded bytes with the generator ground truth.
'''
    procedure = '''# Infrared remote waveform and identification experiment

1. Import `raw/ir_remote_nec.csv` as a `timeseries.table` Dataset. Bind `time_s` in seconds and the measured `VIR` signal in volts.
2. Run **IR waveform / MARK-SPACE analysis** with a nominal 38 kHz carrier, nominal recovery, automatic pretest, and a 0.05 V minimum signal amplitude. Inspect its carrier estimate, burst table, `eventi_mark_space.csv`, report and diagnostic graphs.
3. With the same source Dataset and signal binding, run **IR protocol identification**. It consumes the waveform module's analysis manifest and MARK/SPACE event table.
4. Inspect the ranked candidates and decoded frame. The expected family is NEC, the frame is 32 bits, and the payload bytes are `08 F7 B2 4D`.
5. Rerender one graph through the public Plot.dataset variant and confirm that the scientific event table remains unchanged.

The waveform is deterministic synthetic teaching data generated by this package, not a captured remote signal. Ground truth is in `metadata/ir_remote_ground_truth.txt`.
'''
    (root / 'notes/experiment/objective.md').write_text(objective, encoding='utf-8')
    (root / 'notes/experiment/procedure.md').write_text(procedure, encoding='utf-8')
    (root / 'STUDENT_GUIDE.md').write_text(objective + '\n' + procedure, encoding='utf-8')
    configure(root, 'ir_remote_nec', [dict(
        source='raw/ir_remote_nec.csv', id='ir.remote.source', kind='timeseries.table',
        units={'time_s': 's', 'VIR': 'V'},
        roles={'time_s': 'independent', 'VIR': 'measured'},
    )], [
        dict(id='gxtxt.ir_waveform', sources={'primary': 'ir.remote.source'},
             bindings={'time': 'time_s', 'signal': 'VIR'},
             config={'dataset_id': 'ir.remote.source', 'nominal_carrier_hz': '38000',
                     'carrier_search_mode': 'nominal_recovery', 'pretest_mode': 'auto',
                     'min_signal_amplitude_v': '0.050'}),
        dict(id='gxtxt.ir_identify', sources={'primary': 'ir.remote.source'},
             bindings={'signal': 'VIR'}, config={'dataset_id': 'ir.remote.source'}),
    ], 'Deterministic NEC infrared remote')
    print(f'Generated {total} samples and {len(marks)} MARK intervals')


if __name__ == '__main__':
    main()
