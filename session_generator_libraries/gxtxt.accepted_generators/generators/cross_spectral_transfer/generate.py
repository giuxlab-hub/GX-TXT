#!/usr/bin/env python3
"""Generate synchronized transfer-function teaching data and instructions."""
# SPDX-License-Identifier: GPL-3.0-or-later
from __future__ import annotations

import argparse
import csv
import math
from pathlib import Path
from session_recipe import configure

FS = 4096
WINDOWS = 12
ROWS = FS * WINDOWS
GAIN = 2.5
TONES = (64, 256, 640)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--target-session", required=True)
    parser.add_argument("--library-id")
    parser.add_argument("--generator-id")
    args = parser.parse_args()
    root = Path(args.target_session)
    (root / "raw").mkdir(parents=True, exist_ok=True)
    (root / "metadata").mkdir(parents=True, exist_ok=True)
    (root / "notes/experiment").mkdir(parents=True, exist_ok=True)
    path = root / "raw/cross_spectral_transfer_demo.csv"
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.writer(stream)
        writer.writerow(("time_s", "input_V", "output_V"))
        for index in range(ROWS):
            segment, within = divmod(index, FS)
            phase = 0.19 * segment
            signal = sum(math.sin(2 * math.pi * frequency * within / FS + phase + 0.13 * order) / (order + 1)
                         for order, frequency in enumerate(TONES))
            writer.writerow((f"{index / FS:.12g}", f"{signal:.12g}", f"{GAIN * signal:.12g}"))
    (root / "metadata/cross_spectral_ground_truth.txt").write_text(
        "sample_rate_hz=4096\nwindow_seconds=1\nwindows=12\ntransfer_gain=2.5\n"
        "tones_hz=64;256;640\nexpected_coherence_at_tones=1\n",
        encoding="utf-8")
    objective = """# Experiment objective

Estimate the frequency-dependent transfer function between two synchronized voltage signals. The generated output equals 2.5 times the input, so H1 and H2 magnitude should be 2.5 and coherence should approach 1 at 64, 256 and 640 Hz.
"""
    procedure = """# Cross-spectral transfer experiment

1. Open the generated Session. `cross_spectral.source` is already a canonical Dataset with elapsed-time and voltage units.
2. Inspect the configured `tset_001` Temporal Window Set: twelve non-overlapping one-second windows.
3. Run **Cross-Spectral & Transfer Function Analysis** with the persisted Time/Input/Output bindings, Hann weighting, mean detrending, automatic NFFT and serial workers.
4. Inspect the published spectrum Dataset and the public plot.dataset graphs. At 64, 256 and 640 Hz, compare H1 and H2 magnitude with the known gain 2.5, phase with 0 rad, and coherence with 1.
5. Change only a plot title, axis range or variant and rerender. Verify that the scientific Dataset is reused. Then change a scientific FFT setting and explain why the cached result must be recalculated.

The source is deterministic synthetic teaching data, generated by this package. It is not a measured instrument recording. Preserve the source generator version and ground-truth file with the Session.
"""
    (root / "notes/experiment/objective.md").write_text(objective, encoding="utf-8")
    (root / "notes/experiment/procedure.md").write_text(procedure, encoding="utf-8")
    (root / "STUDENT_GUIDE.md").write_text(objective + "\n" + procedure, encoding="utf-8")
    configure(
        root, "cross_spectral_transfer_demo.csv", "cross_spectral.source",
        "analysis.cross_spectral_transfer",
        {"time_s": "independent", "input_V": "measured", "output_V": "measured"},
        {"time": "time_s", "input_signal": "input_V", "output_signal": "output_V"},
        {"run_mode": "recalculate", "temporal_set": "tset_001", "window": "hann",
         "detrend": "mean", "nfft_mode": "auto", "nfft": "4096", "workers": "serial"},
        {"time_s": "s", "input_V": "V", "output_V": "V"},
    )
    with (root / "metadata/manifest.ini").open("a", encoding="utf-8") as stream:
        stream.write("[temporal_set_api]\nversion=1\nids=tset_001\n\n")
        stream.write("[temporal_set.tset_001]\napi_version=1\nid=tset_001\n")
        stream.write("type=window_set\nsource_dataset_id=cross_spectral.source\n")
        stream.write("temporal_variable_id=v0001\ntemporal_variable=time_s\ntemporal_unit=s\n")
        stream.write("parent_selection_id=\nboundary_policy=start_inclusive_end_exclusive\n")
        stream.write("generator_basis=samples\nwindow_size=4096\nstep=4096\n")
        stream.write("duration_unit=\npartial_policy=drop\n")
        stream.write("label=Twelve synchronized one-second windows\n")
        stream.write("created_at=2026-10-01T00:00:00+0000\nupdated_at=2026-10-01T00:00:00+0000\n")
    print(f"Generated {ROWS} synchronized cross-spectral samples in {path}")


if __name__ == "__main__":
    main()
