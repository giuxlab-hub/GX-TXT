function demo_numeric_nonlinear_fit_main(args)
% Fit the selected canonical Dataset through NUMERIC_API_v1 and validate it
% against the deterministic Nonlinear Fitting Session Generator reference.
% SPDX-License-Identifier: GPL-3.0-or-later
  config_path=arg_value(args,'--config','');
  if(isempty(config_path)), error('demo.numeric.nonlinear_fit: --config is required'); endif
  cfg=gxtxt_ini_read(config_path);
  session=strtrim(gxtxt_ini_get(cfg,'runtime.session',''));
  outdir=strtrim(gxtxt_ini_get(cfg,'runtime.output_dir',''));
  source_id=strtrim(gxtxt_ini_get(cfg,'analysis_source.primary.dataset_id',''));
  if(isempty(source_id)), source_id=strtrim(gxtxt_ini_get(cfg,'dataset.id','')); endif
  x_token=binding_column(gxtxt_ini_get(cfg,'bindings.x',''),'x');
  y_token=binding_column(gxtxt_ini_get(cfg,'bindings.y',''),'y');
  if(isempty(session)||isempty(outdir)||isempty(source_id))
    error('demo.numeric.nonlinear_fit: runtime Session, output directory, or source Dataset is missing');
  endif
  if(isempty(x_token)||isempty(y_token))
    error('demo.numeric.nonlinear_fit: bind both X variable and Y variable before running');
  endif

  [~,~,x_meta]=gxtxt_analysis_source_variable_meta(cfg,'primary',x_token);
  [~,~,y_meta]=gxtxt_analysis_source_variable_meta(cfg,'primary',y_token);
  if(!isfield(x_meta,'found') || !x_meta.found)
    error('demo.numeric.nonlinear_fit: X binding could not be resolved in primary source: %s',x_token);
  endif
  if(!isfield(y_meta,'found') || !y_meta.found)
    error('demo.numeric.nonlinear_fit: Y binding could not be resolved in primary source: %s',y_token);
  endif
  x_var=strtrim(x_meta.variable_id); y_var=strtrim(y_meta.variable_id);
  x_name=strtrim(x_meta.name); y_name=strtrim(y_meta.name);
  if(isempty(x_var)||isempty(y_var))
    error('demo.numeric.nonlinear_fit: selected bindings do not expose stable Dataset variable_id values');
  endif
  if(exist(outdir,'dir')!=7), mkdir(outdir); endif

  truth_path=fullfile(session,'metadata','ground_truth.txt');
  if(exist(truth_path,'file')!=2)
    error(['demo.numeric.nonlinear_fit: metadata/ground_truth.txt is missing. ' ...
           'Use a Session generated by GX-TXT Numerical Examples / Nonlinear Fitting.']);
  endif
  reference=read_ground_truth(truth_path);
  expected=[reference.A reference.k reference.c];

  model=@(p,z) p(1).*exp(-p(2).*z)+p(3);
  opts=struct('solver','auto','max_iterations',500,'tolerance',1e-9);
  result=gxtxt_numeric_v1('dataset_nonlinear_fit',session,source_id,x_var,y_var,model,[4;0.5;0.2],opts);
  recovered=result.parameters(:).';
  tolerance=[0.10,0.05,0.08];
  errors=abs(recovered-expected);
  if(any(!isfinite(recovered))||any(errors>tolerance))
    error('demo.numeric.nonlinear_fit: fit outside reference tolerances: errors=%s tolerances=%s',mat2str(errors),mat2str(tolerance));
  endif

  [x,measured]=read_source_dataset(session,source_id,x_var,y_var);
  fitted=result.predicted(:);
  if(numel(x)!=numel(fitted)), error('demo.numeric.nonlinear_fit: fitted/source length mismatch'); endif

  derived_id='demo.nonlinear.fit';
  publish_fit_dataset(session,derived_id,source_id,x_var,y_var,x,measured,fitted,result);
  write_metrics(outdir,source_id,derived_id,x_var,y_var,x_name,y_name,expected,recovered,errors,tolerance,result,reference);
  write_report(outdir,source_id,derived_id,x_var,y_var,x_name,y_name,expected,recovered,errors,tolerance,result,reference);

  model_name='y = A*exp(-k*x) + c';
  save(fullfile(outdir,'render_cache.mat'),'derived_id','expected','recovered','errors','tolerance','model_name','source_id','x_var','y_var');
  demo_numeric_nonlinear_fit_render(outdir,cfg,derived_id);

  fprintf('PASS demo.numeric.nonlinear_fit: A=%.9g k=%.9g c=%.9g, source=%s, derived=%s\n', ...
          recovered(1),recovered(2),recovered(3),source_id,derived_id);
endfunction

function col=binding_column(value,role)
  col=strtrim(value);
  if(isempty(col)||strcmp(col,'auto')), col=''; return; endif
  dot=find(col=='.',1);
  if(!isempty(dot))
    source=strtrim(col(1:dot-1));
    if(!strcmp(source,'primary'))
      error('demo.numeric.nonlinear_fit: binding %s must refer to primary.*, got %s',role,col);
    endif
    col=strtrim(col(dot+1:end));
  endif
endfunction

function [x,y]=read_source_dataset(session,source_id,x_var,y_var)
  stream=gxtxt_table_stream_open_dataset(session,source_id,{x_var,y_var},4096, ...
          struct('start',0,'count',-1,'require_direct',false,'numeric_transport','auto'));
  x=[]; y=[];
  unwind_protect
    while(!stream.eof)
      [stream,chunk]=gxtxt_table_stream_next(stream);
      if(chunk.nrows>0)
        x=[x;double(chunk.values{1}(:))];
        y=[y;double(chunk.values{2}(:))];
      endif
    endwhile
  unwind_protect_cleanup
    stream=gxtxt_table_stream_close(stream);
  end_unwind_protect
  if(numel(x)<10||numel(x)!=numel(y)||any(!isfinite(x))||any(!isfinite(y)))
    error('demo.numeric.nonlinear_fit: selected Dataset variables do not contain a valid finite nonlinear-fit table');
  endif
endfunction

function R=read_ground_truth(path)
  R=struct('A',NaN,'k',NaN,'c',NaN,'noise','','seed','');
  fid=fopen(path,'r');
  if(fid<0), error('demo.numeric.nonlinear_fit: cannot open ground truth: %s',path); endif
  unwind_protect
    while(true)
      line=fgetl(fid); if(!ischar(line)), break; endif
      tok=regexp(strtrim(line),'^([^=]+)=(.*)$','tokens','once');
      if(isempty(tok)), continue; endif
      key=strtrim(tok{1}); value=strtrim(tok{2});
      if(any(strcmp(key,{'A','k','c'})))
        v=str2double(value); if(!isfinite(v)), error('demo.numeric.nonlinear_fit: invalid reference %s',key); endif
        R.(key)=v;
      elseif(strcmp(key,'noise')), R.noise=value;
      elseif(strcmp(key,'seed')), R.seed=value;
      endif
    endwhile
  unwind_protect_cleanup
    fclose(fid);
  end_unwind_protect
  if(any(!isfinite([R.A R.k R.c]))), error('demo.numeric.nonlinear_fit: ground truth is missing A, k, or c'); endif
endfunction

function publish_fit_dataset(session,derived_id,source_id,x_var,y_var,x,measured,fitted,result)
  options=struct('storage','csv','producer_version','1.0.5', ...
                 'source_dataset_ids',source_id,'source_variable_ids',[x_var ';' y_var], ...
                 'provenance','NUMERIC_API_v1 dataset_nonlinear_fit', ...
                 'replace_owned',true);
  P=gxtxt_publication_v2_open(session,'demo.numeric.nonlinear_fit',derived_id,'table.generic',options);
  complete=false;
  unwind_protect
    P=gxtxt_publication_v2_declare_dimension(P,'row',0,true);
    P=gxtxt_publication_v2_declare_variable(P,'x',struct('name','x','unit',result.x_unit,'dtype','float64','dimension_ids','row','semantic_role','independent','coordinate_role','coordinate'));
    P=gxtxt_publication_v2_declare_variable(P,'measured',struct('name','measured','unit',result.y_unit,'dtype','float64','dimension_ids','row','semantic_role','measured','coordinate_variable_ids','x'));
    P=gxtxt_publication_v2_declare_variable(P,'fitted',struct('name','fitted','unit',result.y_unit,'dtype','float64','dimension_ids','row','semantic_role','fitted','coordinate_variable_ids','x'));
    P=gxtxt_publication_v2_append(P,'row',{'x',x;'measured',measured;'fitted',fitted});
    [P,published]=gxtxt_publication_v2_finalize(P); complete=true;
  unwind_protect_cleanup
    if(!complete), try P=gxtxt_publication_v2_abort(P); catch; end_try_catch, endif
  end_unwind_protect
endfunction

function write_metrics(outdir,source_id,derived_id,x_var,y_var,x_name,y_name,expected,recovered,errors,tolerance,result,reference)
  names={'A','k','c'};
  path=fullfile(outdir,'fit_metrics.ini'); fid=fopen(path,'w');
  if(fid<0), error('demo.numeric.nonlinear_fit: cannot write metrics'); endif
  unwind_protect
    fprintf(fid,'[fit]\nsource_dataset_id=%s\nx_variable_id=%s\ny_variable_id=%s\nx_variable_name=%s\ny_variable_name=%s\nderived_dataset_id=%s\nmodel=y=A*exp(-k*x)+c\n',source_id,x_var,y_var,x_name,y_name,derived_id);
    for i=1:3
      fprintf(fid,'expected_%s=%.15g\nrecovered_%s=%.15g\nabsolute_error_%s=%.15g\ntolerance_%s=%.15g\n', ...
              names{i},expected(i),names{i},recovered(i),names{i},errors(i),names{i},tolerance(i));
    endfor
    fprintf(fid,'solver=%s\nconverged=%d\nsse=%.15g\nrmse=%.15g\nr_squared=%.15g\nnoise=%s\nseed=%s\n', ...
            result.solver,result.converged,result.sse,result.rmse,result.r_squared,reference.noise,reference.seed);
  unwind_protect_cleanup
    fclose(fid);
  end_unwind_protect
endfunction

function write_report(outdir,source_id,derived_id,x_var,y_var,x_name,y_name,expected,recovered,errors,tolerance,result,reference)
  names={'A','k','c'};
  path=fullfile(outdir,'fit_report.txt'); fid=fopen(path,'w');
  if(fid<0), error('demo.numeric.nonlinear_fit: cannot write report'); endif
  unwind_protect
    fprintf(fid,'Nonlinear fitting: y = A*exp(-k*x) + c\n');
    fprintf(fid,'Canonical Session generator: GX-TXT Numerical Examples / Nonlinear Fitting\n');
    fprintf(fid,'Source Dataset: %s; X variable: %s (%s); Y variable: %s (%s)\n',source_id,x_name,x_var,y_name,y_var);
    fprintf(fid,'Derived Dataset: %s\n',derived_id);
    fprintf(fid,'Generator noise: %s; seed: %s\n',reference.noise,reference.seed);
    for i=1:3
      fprintf(fid,'%s: expected %.9g; recovered %.9g; absolute error %.9g; tolerance %.9g\n', ...
              names{i},expected(i),recovered(i),errors(i),tolerance(i));
    endfor
    fprintf(fid,'Solver: %s; converged: %d; SSE: %.9g; RMSE: %.9g; R-squared: %.9g\n', ...
            result.solver,result.converged,result.sse,result.rmse,result.r_squared);
  unwind_protect_cleanup
    fclose(fid);
  end_unwind_protect
endfunction

function value=arg_value(args,name,default_value)
  value=default_value;
  for i=1:(numel(args)-1), if(strcmp(args{i},name)), value=args{i+1}; return; endif, endfor
endfunction
